"""Rasterize the Ukraine oblast map (same SVG paths as the Vitalnya TV launcher)
into a per-pixel region-index bitmap for the firmware.
0 = background, 1..N = region (order of REGIONS), 255 = border line."""
import json, re, sys
from PIL import Image, ImageDraw, ImageChops

W, H = 296, 200            # map area on the 296x240 screen (below a 40 px header)
VB_W, VB_H = 508, 340
S = 4                      # supersampling for clean edges

d = json.load(open(sys.argv[1]))
regions = [r[0] for r in d["REGIONS"]]
scale = min(W / VB_W, H / VB_H)
ox = (W - VB_W * scale) / 2
oy = (H - VB_H * scale) / 2

def subpaths(path):
    out, cur = [], []
    for cmd, args in re.findall(r"([MLZ])([^MLZ]*)", path):
        nums = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", args)]
        pts = list(zip(nums[0::2], nums[1::2]))
        if cmd == "M":
            if len(cur) > 2: out.append(cur)
            cur = list(pts)
        elif cmd == "L":
            cur += pts
        elif cmd == "Z":
            if len(cur) > 2: out.append(cur)
            cur = []
    if len(cur) > 2: out.append(cur)
    return out

idx = Image.new("L", (W * S, H * S), 0)
for i, rid in enumerate(regions, start=1):
    mask = Image.new("1", idx.size, 0)
    for sp in subpaths(d["UA_PATHS"][rid]):
        m = Image.new("1", idx.size, 0)
        ImageDraw.Draw(m).polygon([((x * scale + ox) * S, (y * scale + oy) * S) for x, y in sp], fill=1)
        mask = ImageChops.logical_xor(mask, m)   # even-odd fill
    idx.paste(i, mask=mask)

small = idx.resize((W, H), Image.NEAREST)
px = small.load()
out = bytearray(W * H)
for y in range(H):
    for x in range(W):
        v = px[x, y]
        border = False
        if v:
            for dx, dy in ((1, 0), (0, 1), (-1, 0), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < W and 0 <= ny < H and px[nx, ny] != v and (px[nx, ny] != 0 or dx > 0 or dy > 0):
                    border = True
        out[y * W + x] = 255 if border else v

kx, ky = d["KYIV_XY"]
kyiv = (round(kx * scale + ox), round(ky * scale + oy))

# preview for sanity check
pal = Image.new("RGB", (W, H))
pp = pal.load()
for y in range(H):
    for x in range(W):
        v = out[y * W + x]
        pp[x, y] = (20, 22, 28) if v == 0 else (230, 230, 230) if v == 255 else ((200, 40, 40) if regions[v - 1] in ("khr", "sum", "don", "kyiv") else (70, 74, 84))
ImageDraw.Draw(pal).ellipse([kyiv[0] - 3, kyiv[1] - 3, kyiv[0] + 3, kyiv[1] + 3], fill=(255, 255, 255))
pal.resize((W * 3, H * 3), Image.NEAREST).save(sys.argv[2] + "/map_preview.png")

# region label anchors (centroids) for the firmware
cent = {k: (round(v[0] * scale + ox), round(v[1] * scale + oy)) for k, v in d["UA_CENT"].items()}

with open(sys.argv[2] + "/ua_map.h", "w") as f:
    f.write("// generated by make_map.py — Ukraine oblasts, region-index bitmap\n#pragma once\n#include <cstdint>\n\n")
    f.write(f"#define UA_MAP_W {W}\n#define UA_MAP_H {H}\n#define UA_REGION_COUNT {len(regions)}\n")
    f.write(f"#define UA_KYIV_X {kyiv[0]}\n#define UA_KYIV_Y {kyiv[1]}\n\n")
    f.write("// region ids in bitmap order (index+1 in the bitmap)\n")
    f.write("static const char* const kUaRegionIds[UA_REGION_COUNT] = {" + ",".join(f'"{r}"' for r in regions) + "};\n")
    f.write("static const int16_t kUaRegionCentroid[UA_REGION_COUNT][2] = {" +
            ",".join("{%d,%d}" % cent.get(r, (0, 0)) for r in regions) + "};\n\n")
    f.write("static const uint8_t kUaMap[UA_MAP_W * UA_MAP_H] = {\n")
    for i in range(0, len(out), 40):
        f.write("  " + ",".join(str(b) for b in out[i:i + 40]) + ",\n")
    f.write("};\n")
print("ok", W, H, "kyiv", kyiv, "regions", len(regions))
