"""Generate siren / all-clear sounds as OGG Opus (16 kHz mono, 60 ms frames)
and emit them as C arrays for the firmware. Uses system libopus via ctypes."""
import ctypes, math, random, struct, sys

SR = 16000
FRAME = SR * 60 // 1000  # 960 samples = 60 ms (xiaozhi assumes 60 ms frames)

opus = ctypes.CDLL("libopus.so.0")
opus.opus_encoder_create.restype = ctypes.c_void_p
opus.opus_encoder_create.argtypes = [ctypes.c_int32, ctypes.c_int, ctypes.c_int, ctypes.POINTER(ctypes.c_int)]
opus.opus_encode.restype = ctypes.c_int32
opus.opus_encode.argtypes = [ctypes.c_void_p, ctypes.POINTER(ctypes.c_int16), ctypes.c_int, ctypes.c_char_p, ctypes.c_int32]
opus.opus_encoder_ctl.argtypes = [ctypes.c_void_p, ctypes.c_int, ctypes.c_int32]
OPUS_APPLICATION_AUDIO = 2049
OPUS_SET_BITRATE = 4002

# ---------- OGG muxer ----------
def _crc_table():
    t = []
    for i in range(256):
        r = i << 24
        for _ in range(8):
            r = ((r << 1) ^ 0x04C11DB7) if r & 0x80000000 else (r << 1)
        t.append(r & 0xFFFFFFFF)
    return t
CRC = _crc_table()
def crc32(data):
    c = 0
    for b in data:
        c = ((c << 8) ^ CRC[((c >> 24) ^ b) & 0xFF]) & 0xFFFFFFFF
    return c

def page(packet, granule, seq, flags, serial=0x5A1E7):
    segs = []
    n = len(packet)
    while n >= 255:
        segs.append(255); n -= 255
    segs.append(n)
    hdr = b"OggS" + struct.pack("<BBqIII", 0, flags, granule, serial, seq, 0) + bytes([len(segs)]) + bytes(segs)
    p = bytearray(hdr + packet)
    struct.pack_into("<I", p, 22, crc32(p))
    return bytes(p)

def encode_ogg(samples):
    err = ctypes.c_int()
    enc = opus.opus_encoder_create(SR, 1, OPUS_APPLICATION_AUDIO, ctypes.byref(err))
    assert err.value == 0
    opus.opus_encoder_ctl(enc, OPUS_SET_BITRATE, 32000)
    head = b"OpusHead" + struct.pack("<BBHIhB", 1, 1, 312, SR, 0, 0)
    tags = b"OpusTags" + struct.pack("<I", 7) + b"vitalnya" + struct.pack("<I", 0)
    out = [page(head, 0, 0, 0x02), page(tags, 0, 1, 0)]
    while len(samples) % FRAME:
        samples.append(0)
    nframes = len(samples) // FRAME
    buf = ctypes.create_string_buffer(4000)
    gran = 312
    for i in range(nframes):
        pcm = (ctypes.c_int16 * FRAME)(*samples[i * FRAME:(i + 1) * FRAME])
        n = opus.opus_encode(enc, pcm, FRAME, buf, 4000)
        assert n > 0, n
        gran += FRAME * 48000 // SR  # granule in 48 kHz units
        out.append(page(buf.raw[:n], gran, i + 2, 0x04 if i == nframes - 1 else 0))
    return b"".join(out)

def clip(x):
    return max(-32767, min(32767, int(x)))

# ---------- sounds ----------
def siren(cycles=3, period=4.0, lo=380.0, hi=1050.0, vol=0.75):
    """Classic air-raid siren: slow wail up and down, slightly rough timbre."""
    out, ph = [], 0.0
    total = int(SR * cycles * period)
    for i in range(total):
        t = i / SR
        pos = (t % period) / period
        k = 0.5 - 0.5 * math.cos(2 * math.pi * pos)      # 0 -> 1 -> 0
        f = lo + (hi - lo) * k
        ph += 2 * math.pi * f / SR
        s = math.sin(ph) + 0.35 * math.sin(2 * ph) + 0.18 * math.sin(3 * ph)
        env = min(1.0, t / 0.4, (cycles * period - t) / 0.6)
        out.append(clip(s / 1.53 * vol * env * 32767))
    return out

def chime(notes, note_len=0.55, vol=0.6):
    """Soft bell-like ascending notes (all-clear)."""
    out = []
    for f in notes:
        n = int(SR * note_len)
        for i in range(n):
            t = i / SR
            env = math.exp(-t * 4.0) * min(1.0, t / 0.01)
            s = math.sin(2 * math.pi * f * t) + 0.3 * math.sin(2 * math.pi * 2 * f * t)
            out.append(clip(s / 1.3 * vol * env * 32767))
    out += [0] * int(SR * 0.3)
    return out

def beep(vol=0.5):
    out = []
    for f in (880, 660):
        n = int(SR * 0.18)
        for i in range(n):
            t = i / SR
            env = min(1.0, t / 0.01, (0.18 - t) / 0.02)
            out.append(clip(math.sin(2 * math.pi * f * t) * vol * env * 32767))
        out += [0] * int(SR * 0.06)
    return out

def to_c(name, data):
    lines = [f"// generated by make_sounds.py\n#pragma once\n#include <cstdint>\n#include <cstddef>\n",
             f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const size_t {name}_len = {len(data)};\n")
    return "\n".join(lines)

if __name__ == "__main__":
    outdir = sys.argv[1]
    sounds = {
        "kSirenOgg": siren(),
        "kAllClearOgg": chime([523.25, 659.25, 783.99, 1046.5]),
        "kBeepOgg": beep(),
    }
    for name, pcm in sounds.items():
        ogg = encode_ogg(pcm)
        with open(f"{outdir}/{name}.ogg", "wb") as f:
            f.write(ogg)
        print(name, len(pcm) / SR, "s ->", len(ogg), "bytes")
    with open(f"{outdir}/alert_sounds.h", "w") as f:
        f.write("// generated by make_sounds.py\n#pragma once\n#include <cstdint>\n#include <cstddef>\n\n")
        for name in sounds:
            data = open(f"{outdir}/{name}.ogg", "rb").read()
            body = to_c(name, data).split("\n", 4)[-1]
            f.write(body + "\n")
